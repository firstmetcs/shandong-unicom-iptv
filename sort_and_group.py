def sort_tv_channel(target_list):
	order_list = cctv + shandong + province + other + carousel + qingdao
	order_index = {val: idx for idx, val in enumerate(order_list)}
	sorted_list = sorted(target_list, key=lambda x: order_index.get(x[1], float('inf')))
	return sorted_list

def get_tv_group_title(value):
	if (value in cctv):
		return "央视频道"
	if (value in shandong):
		return "山东频道"
	if (value in province):
		return "卫视频道"
	if (value in other):
		return "其他频道"
	if (value in carousel):
		return "轮播频道"
	if (value in qingdao):
		return "山东频道"
	return "其他频道"



